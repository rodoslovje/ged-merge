/**
 * Generates `src/tools/conformance/spec70.ts`, the GEDCOM 7.0 structure table
 * the health check's conformance pass reads.
 *
 * The source is the machine-readable extract FamilySearch publishes alongside
 * the 7.0 specification (repository FamilySearch/GEDCOM, folder
 * `extracted-files/`): which structure each tag names under each
 * superstructure (`substructures.tsv`), how many times it may appear
 * (`cardinalities.tsv`), what its line value is (`payloads.tsv`) and the
 * enumerated value sets (`enumerations.tsv`, `enumerationsets.tsv`). Nothing in
 * the generated table is typed by hand, so a spec revision is a re-run.
 *
 * Run:  node scripts/gedcom7-spec-table.ts            (downloads the extract)
 *       node scripts/gedcom7-spec-table.ts <dir>      (reads the TSVs from <dir>)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/tools/conformance/spec70.ts");
const BASE = "https://raw.githubusercontent.com/FamilySearch/GEDCOM/main/extracted-files";
const V7 = "https://gedcom.io/terms/v7/";
const FILES = ["substructures", "cardinalities", "payloads", "enumerations", "enumerationsets"] as const;

async function load(name: string): Promise<string[][]> {
  const dir = process.argv[2];
  const text = dir
    ? readFileSync(resolve(dir, `${name}.tsv`), "utf8")
    : await (await fetch(`${BASE}/${name}.tsv`)).text();
  return text
    .split(/\r?\n/)
    .slice(1)
    .filter((l) => l.trim())
    .map((l) => l.split("\t").map((c) => c.trim()));
}

const short = (uri: string): string => (uri.startsWith(V7) ? uri.slice(V7.length) : uri);
/** An enumeration value's tag: the last part of its term ("enum-ADOP-HUSB" → HUSB,
 *  "INDI-RELI" → RELI, "enum-PRE_1970" → PRE_1970). */
const enumTag = (uri: string): string => short(uri).split("-").pop()!;
const CARD: Record<string, string> = { "{0:1}": "01", "{1:1}": "11", "{0:M}": "0M", "{1:M}": "1M" };

const [subs, cards, payloads, enums, enumSets] = await Promise.all(FILES.map(load));

const card = new Map<string, string>();
for (const [sup, struct, c] of cards) card.set(`${short(sup)} ${short(struct)}`, CARD[c] ?? c);

const enumOf = new Map<string, string>();
for (const [struct, set] of enums) enumOf.set(short(struct), short(set));
const setValues = new Map<string, string[]>();
for (const [set, value] of enumSets) {
  const key = short(set);
  setValues.set(key, [...(setValues.get(key) ?? []), enumTag(value)]);
}

/** The payload code the checker reads (see `SpecTable` in ./conformance/types). */
function payloadCode(struct: string, payload: string): string {
  const p = short(payload).replaceAll(V7, "");
  const ptr = /^@<record-([A-Z]+)>@$/.exec(p);
  if (ptr) return `@${ptr[1]}`;
  if (p === "Y|<NULL>") return "Y";
  if (p === "type-Enum") return `E:${enumOf.get(struct)}`;
  if (p === "type-List#Enum") return `L:${enumOf.get(struct)}`;
  if (p.startsWith("type-Date")) return "D";
  if (p === "type-Age") return "A";
  if (p.endsWith("#Language")) return "G";
  if (p === "") return "";
  return "T";
}

const structs = new Map<string, { payload: string; children: string[] }>();
const entry = (id: string) => {
  let e = structs.get(id);
  if (!e) structs.set(id, (e = { payload: "", children: [] }));
  return e;
};
for (const [struct, payload] of payloads) entry(short(struct)).payload = payloadCode(short(struct), payload);

const roots: Record<string, string> = {};
for (const [sup, tag, struct] of subs) {
  const id = short(struct);
  entry(id);
  if (!sup) {
    if (tag !== "CONT") roots[tag] = id;
    continue;
  }
  const c = card.get(`${short(sup)} ${id}`);
  if (!c) throw new Error(`no cardinality for ${tag} (${id}) under ${short(sup)}`);
  entry(short(sup)).children.push(id === tag ? `${tag}:${c}` : `${tag}=${id}:${c}`);
}

// Identical child lists (the twenty-odd individual events share one) are
// written once and referenced by index.
const lists: string[] = [];
const listIndex = new Map<string, number>();
const rows: string[] = [];
for (const id of [...structs.keys()].sort()) {
  const { payload, children } = structs.get(id)!;
  if (id === "CONT") continue;
  const list = children.sort().join(" ");
  let i = listIndex.get(list);
  if (i === undefined) {
    i = lists.length;
    lists.push(list);
    listIndex.set(list, i);
  }
  rows.push(`    ${JSON.stringify(id)}: [${JSON.stringify(payload)}, L[${i}]],`);
}
const enumRows = [...setValues.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([set, values]) => `    ${JSON.stringify(set)}: ${JSON.stringify(values.sort().join(" "))},`);

const out = `// GENERATED by scripts/gedcom7-spec-table.ts from the GEDCOM 7.0 extract
// (FamilySearch/GEDCOM, extracted-files/*.tsv). Do not edit by hand — re-run it.
import type { SpecTable } from "./types";

/** Child lists shared by several structures (see \`SpecTable.structs\`). */
const L: string[] = [
${lists.map((l) => `  ${JSON.stringify(l)},`).join("\n")}
];

export const SPEC_70: SpecTable = {
  version: "7.0",
  roots: ${JSON.stringify(roots)},
  structs: {
${rows.join("\n")}
  },
  enums: {
${enumRows.join("\n")}
  },
};
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${structs.size} structures, ${lists.length} child lists, ${setValues.size} enum sets`);
